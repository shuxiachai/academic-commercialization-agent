/* Result view: scorecard, report, sources, and failed-retrieval diagnostics. */

import * as api from "./api.js";
import { t } from "./i18n.js";

/* ── Scoring dimensions ────────────────────────────────────────────────
 * Maxima differ per dimension (TRL is out of 9, MRL out of 10, the rest out
 * of 5), so a bar cannot assume a shared scale. Declared here rather than
 * inferred, because a wrong denominator silently misdraws the bar. */
const DIMENSIONS = [
  { key: "trl_score",            max: 9,  label: "dim_trl" },
  { key: "mrl_score",            max: 10, label: "dim_mrl" },
  { key: "patent_strength",      max: 5,  label: "dim_patent" },
  { key: "market_accessibility", max: 5,  label: "dim_market" },
  { key: "evidence_confidence",  max: 5,  label: "dim_evidence" },
];

/** Band for the headline number. Thresholds match the scorecard the Python
 *  side renders, so the same run does not get two different verdicts. */
function band(score) {
  if (score >= 70) return { name: t("band_strong"), tone: "success" };
  if (score >= 55) return { name: t("band_moderate"), tone: "accent" };
  if (score >= 40) return { name: t("band_early"), tone: "warning" };
  return { name: t("band_nascent"), tone: "muted" };
}

const el = (tag, className, text) => {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text != null) node.textContent = text;
  return node;
};

/* ── Markdown ──────────────────────────────────────────────────────────
 * A deliberately small subset: the reports are generated by our own prompt,
 * so the shapes that appear are known. Anything unrecognised falls through
 * as a paragraph rather than being dropped.
 *
 * Input is escaped before any markup is added — the report contains model
 * output and third-party titles, and must never reach innerHTML unescaped. */
function escapeHtml(text) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    // Quotes matter as much as angle brackets here: inline() goes on to build
    // <a href="..."> by substitution, so a link target carrying a quote could
    // otherwise close the attribute and open an event handler beside it
    // ([x](https://e.test/" onmouseover="…)). Escaping happens before that
    // substitution runs, so the URL is already inert by the time it is placed
    // in the attribute. Report text is model output plus third-party result
    // titles and URLs — none of it is ours to trust.
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function inline(text) {
  return escapeHtml(text)
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    .replace(/(?<!\*)\*(?!\s)(.+?)(?<!\s)\*(?!\*)/g, "<em>$1</em>")
    .replace(/`(.+?)`/g, "<code>$1</code>")
    // Citation markers get their own affordance: they are the reason the
    // report is auditable, and running them together with prose hides that.
    .replace(/\[([APM]\d+(?:\s*,\s*[APM]\d+)*)\]/g,
             '<span class="cite">[$1]</span>')
    .replace(/\[([^\]]+)\]\((https?:\/\/[^)]+)\)/g,
             '<a href="$2" target="_blank" rel="noopener noreferrer">$1</a>');
}

export function renderMarkdown(md) {
  const out = [];
  const lines = md.split("\n");
  let paragraph = [];
  let list = null;
  let table = null;

  const flushParagraph = () => {
    if (paragraph.length) {
      out.push(`<p>${inline(paragraph.join(" "))}</p>`);
      paragraph = [];
    }
  };
  const flushList = () => {
    if (list) {
      out.push(`<ul>${list.map((i) => `<li>${inline(i)}</li>`).join("")}</ul>`);
      list = null;
    }
  };
  const flushTable = () => {
    if (table && table.rows.length) {
      const head = `<tr>${table.head.map((c) => `<th>${inline(c)}</th>`).join("")}</tr>`;
      const body = table.rows
        .map((r) => `<tr>${r.map((c) => `<td>${inline(c)}</td>`).join("")}</tr>`)
        .join("");
      out.push(`<div class="table-wrap"><table><thead>${head}</thead><tbody>${body}</tbody></table></div>`);
    }
    table = null;
  };
  const flushAll = () => { flushParagraph(); flushList(); flushTable(); };

  for (const raw of lines) {
    const line = raw.trimEnd();

    if (!line.trim()) { flushAll(); continue; }

    const heading = line.match(/^(#{1,4})\s+(.*)$/);
    if (heading) {
      flushAll();
      const level = heading[1].length;
      out.push(`<h${level}>${inline(heading[2])}</h${level}>`);
      continue;
    }

    // A separator row belongs to the table above it and renders nothing.
    if (/^\|[\s|:-]+\|$/.test(line)) continue;

    if (line.startsWith("|") && line.endsWith("|")) {
      const cells = line.slice(1, -1).split("|").map((c) => c.trim());
      flushParagraph(); flushList();
      if (!table) table = { head: cells, rows: [] };
      else table.rows.push(cells);
      continue;
    }
    flushTable();

    const item = line.match(/^\s*[-*]\s+(.*)$/);
    if (item) {
      flushParagraph();
      (list ??= []).push(item[1]);
      continue;
    }
    flushList();

    paragraph.push(line.trim());
  }
  flushAll();
  return out.join("\n");
}

/* ── Scorecard ─────────────────────────────────────────────────────── */

function renderScorecard(scores) {
  const wrap = el("section", "scorecard");
  const overall = Number(scores.overall_score ?? 0);
  const { name, tone } = band(overall);

  const head = el("div", "scorecard__head");
  const figure = el("div", "scorecard__figure");
  figure.dataset.tone = tone;
  figure.append(
    el("span", "scorecard__value tabular", overall.toFixed(1)),
    el("span", "scorecard__denom", "/ 100"),
  );
  const caption = el("div", "scorecard__caption");
  caption.append(
    el("span", "scorecard__band", name),
    el("span", "scorecard__label", t("readiness")),
  );
  head.append(figure, caption);
  wrap.append(head);

  const grid = el("div", "dims");
  for (const dim of DIMENSIONS) {
    const value = Number(scores[dim.key] ?? 0);
    const pct = Math.max(0, Math.min(100, (value / dim.max) * 100));

    const row = el("div", "dim");
    const label = el("div", "dim__label", t(dim.label));
    const bar = el("div", "dim__bar");
    const fill = el("div", "dim__fill");
    fill.style.width = `${pct}%`;
    bar.append(fill);
    const num = el("div", "dim__value tabular", `${value} / ${dim.max}`);

    row.append(label, bar, num);

    const rationale = scores[dim.key.replace(/_score$|_strength$|_accessibility$|_confidence$/, "") + "_rationale"];
    if (rationale) row.title = rationale;

    grid.append(row);
  }
  wrap.append(grid);

  for (const [key, title] of [["key_risks", t("risks")], ["key_opportunities", t("opportunities")]]) {
    const items = scores[key];
    if (!Array.isArray(items) || !items.length) continue;
    const block = el("div", "notes");
    block.append(el("h4", "notes__title", title));
    const ul = el("ul", "notes__list");
    for (const item of items) ul.append(el("li", null, item));
    block.append(ul);
    wrap.append(block);
  }

  return wrap;
}

export function decisionApplicability(gate) {
  if (!gate) return null;
  const provenance = gate.threshold_provenance?.status ?? "unknown";
  return {
    mode: gate.mode ?? "unknown",
    provenance,
    applicability: t(
      gate.go_no_go_allowed ? "decision_go_allowed" : "decision_go_not_allowed",
    ),
  };
}

function renderDecisionApplicability(gate) {
  const summary = decisionApplicability(gate);
  if (!summary) return null;
  const wrap = el("section", "decision-applicability");
  wrap.append(el("span", "decision-applicability__title", t("decision_applicability_title")));
  const details = el("p", "decision-applicability__detail");
  details.append(
    document.createTextNode(t("decision_mode") + ": "),
    el("code", null, summary.mode),
    document.createTextNode(". "),
  );
  details.append(
    document.createTextNode(summary.applicability + " "),
    document.createTextNode(t("decision_threshold_provenance") + ": "),
    el("code", null, summary.provenance),
  );
  wrap.append(details);
  return wrap;
}

/* ── Public ────────────────────────────────────────────────────────── */

export async function render(container, runId, progress) {
  container.innerHTML = "";
  const artifacts = progress.artifacts ?? [];

  const tabs = el("div", "tabs");
  const panels = el("div", "panels");

  const views = [];
  if (artifacts.includes("scores")) views.push({ id: "score", label: t("tab_score") });
  if (artifacts.includes("report")) views.push({ id: "report", label: t("tab_report") });
  if (artifacts.includes("sources")) views.push({ id: "sources", label: t("tab_sources") });
  if (artifacts.includes("grounding"))
    views.push({ id: "grounding", label: t("tab_grounding") });
  if (artifacts.includes("consistency"))
    views.push({ id: "consistency", label: t("tab_consistency") });
  if (artifacts.includes("retrieval"))
    views.push({ id: "retrieval", label: t("tab_retrieval") });
  if (artifacts.includes("report-audit"))
    views.push({ id: "report-audit", label: t("tab_report_audit") });

  if (!views.length) {
    container.append(el("p", "empty-note", t("no_artifacts")));
    return;
  }

  // Above the tabs, not inside one. Every finding it summarises was already
  // being computed and written to disk, and every one of them qualifies the
  // score — so a reader has to meet them before the number, not after
  // choosing to go looking in a tab.
  const reliability = renderReliability(progress);
  const applicability = renderDecisionApplicability(progress.decision_gate);
  if (applicability) container.append(applicability);
  if (reliability) container.append(reliability);

  for (const view of views) {
    const tab = el("button", "tab", view.label);
    tab.type = "button";
    tab.dataset.view = view.id;
    tab.addEventListener("click", () => select(view.id));
    tabs.append(tab);

    const panel = el("div", "panel");
    panel.dataset.view = view.id;
    panel.hidden = true;
    panels.append(panel);
  }

  container.append(tabs, panels);

  const loaded = new Set();

  async function select(id) {
    for (const tab of tabs.children) tab.dataset.active = String(tab.dataset.view === id);
    for (const panel of panels.children) panel.hidden = panel.dataset.view !== id;

    if (loaded.has(id)) return;
    loaded.add(id);

    const panel = panels.querySelector(`[data-view="${id}"]`);
    panel.append(el("div", "skeleton", ""));

    try {
      if (id === "score") {
        const scores = await api.getArtifact(runId, "scores");
        panel.innerHTML = "";
        panel.append(renderScorecard(scores));
      } else if (id === "report") {
        const md = await api.getReport(runId);
        panel.innerHTML = `<article class="prose">${renderMarkdown(md)}</article>`;
      } else if (id === "grounding") {
        const grounding = await api.getArtifact(runId, "grounding");
        panel.innerHTML = "";
        panel.append(renderGrounding(grounding));
      } else if (id === "consistency") {
        const consistency = await api.getArtifact(runId, "consistency");
        panel.innerHTML = "";
        panel.append(renderConsistency(consistency));
      } else if (id === "retrieval") {
        const diagnostics = await api.getArtifact(runId, "retrieval");
        panel.innerHTML = "";
        panel.append(renderRetrievalDiagnostics(diagnostics));
      } else if (id === "report-audit") {
        const audit = await api.getArtifact(runId, "report-audit");
        panel.innerHTML = "";
        panel.append(renderReportAudit(audit));
      } else {
        const sources = await api.getArtifact(runId, "sources");
        panel.innerHTML = "";
        panel.append(renderSources(sources));
      }
    } catch (err) {
      panel.innerHTML = "";
      panel.append(el("p", "empty-note", err.message));
      loaded.delete(id);      // let a retry re-fetch
    }
  }

  select(views[0].id);
}

/* ── Citation check ────────────────────────────────────────────────────
 * What the server could and could not verify about the report's numbers.
 *
 * The counts are shown together on purpose. "0 unsupported" alone reads as a
 * clean bill of health, when next to a large "could not check" it means the
 * screen mostly did not run — a different statement, and the one a reader
 * needs in order to know how much the first number is worth.
 */

// Exported for the same reason renderMarkdown is: the app calls it only
// through render(), but what it decides — how three counts are presented
// relative to each other — is worth asserting on directly.
export function renderGrounding(data) {
  const wrap = el("div", "grounding");

  const checked = data.checked ?? 0;
  const ungrounded = data.ungrounded ?? 0;
  const unverifiable = data.unverifiable ?? 0;

  wrap.append(el("p", "grounding__lede", t("grounding_lede")));

  const stats = el("div", "grounding__stats");
  for (const [value, label, tone] of [
    [checked, t("grounding_checked"), "ok"],
    [ungrounded, t("grounding_ungrounded"), ungrounded ? "warn" : "ok"],
    [unverifiable, t("grounding_unverifiable"), "muted"],
  ]) {
    const cell = el("div", `grounding__stat grounding__stat--${tone}`);
    cell.append(el("div", "grounding__value", String(value)));
    cell.append(el("div", "grounding__label", label));
    stats.append(cell);
  }
  wrap.append(stats);

  const duplicatesCollapsed = data.duplicates_collapsed ?? 0;
  if (duplicatesCollapsed > 0) {
    const note = t("grounding_duplicates").replace(
      "{count}", String(duplicatesCollapsed),
    );
    wrap.append(el("p", "grounding__lede", note));
  }

  // Per domain, because one aggregate cannot say both "the check works" and
  // "market reports have no abstract to check against".
  const byDomain = data.by_domain ?? {};
  const domains = [
    ["academic", t("group_academic")],
    ["patent", t("group_patents")],
    ["market", t("group_market")],
  ].filter(([key]) => byDomain[key]);

  if (domains.length) {
    const list = el("ul", "grounding__domains");
    for (const [key, label] of domains) {
      const d = byDomain[key];
      const total = (d.checked ?? 0) + (d.unverifiable ?? 0);
      const text = total
        ? `${label}: ${d.checked}/${total} ${t("grounding_checkable")}`
        : `${label}: ${t("grounding_no_figures")}`;
      list.append(el("li", "grounding__domain", text));
    }
    wrap.append(list);
  }

  const rows = data.findings ?? [];
  if (!rows.length) return wrap;

  const list = el("ul", "grounding__list");
  for (const row of rows) {
    const item = el("li", `grounding__item grounding__item--${row.status}`);
    item.append(el("span", "grounding__id", `${row.finding_id}`));
    item.append(el("span", "grounding__claim", row.claim ?? ""));
    const why = row.status === "ungrounded"
      ? t("grounding_missing").replace("{figures}",
          (row.ungrounded_figures ?? []).join(", "))
      : row.unverifiable_reason ?? "";
    if (why) item.append(el("span", "grounding__why", why));
    list.append(item);
  }
  wrap.append(el("h3", "sources__title", t("grounding_detail")));
  wrap.append(list);
  return wrap;
}

/* ── Failed retrieval diagnostics ─────────────────────────────────────
 * A failed pre-agent run has no validated_sources.json, so this is the only
 * durable explanation of what the search layer understood and rejected.
 * Every third-party string is assigned through textContent via el(); none of
 * the audit data is trusted as HTML.
 */
export function renderRetrievalDiagnostics(data) {
  const wrap = el("div", "sources");
  wrap.append(el("p", "grounding__lede", t("retrieval_lede")));

  const accepted = Number(data.accepted_sources ?? 0);
  const required = Number(data.required_sources ?? 0);
  const count = t("retrieval_count")
    .replace("{accepted}", String(accepted))
    .replace("{required}", String(required));
  wrap.append(el("p", "consistency__clear", count));

  const aliases = Array.isArray(data.aliases) && data.aliases.length
    ? data.aliases.join(" · ")
    : "—";
  const fields = [
    [t("retrieval_input"), data.input_topic || "—"],
    [t("retrieval_search"), data.search_topic || "—"],
    [t("retrieval_aliases"), aliases],
  ];
  const plan = el("ul", "sources__list");
  for (const [label, value] of fields) {
    const row = el("li", "source");
    row.append(
      el("span", "source__id", label),
      el("span", "source__body", value),
    );
    plan.append(row);
  }
  wrap.append(plan, el("h3", "sources__title", t("retrieval_audit")));

  const audit = Array.isArray(data.audit) ? data.audit : [];
  if (!audit.length) {
    wrap.append(el("p", "empty-note", t("retrieval_no_audit")));
    return wrap;
  }

  const auditList = el("ul", "sources__list");
  for (const entry of audit) {
    const item = el("li", "source");
    const body = el("div", "source__body");
    body.append(el("span", "source__link", entry.query || "—"));
    const summary = t("retrieval_query_summary")
      .replace("{domain}", entry.domain || "academic")
      .replace("{results}", String(entry.result_count ?? 0))
      .replace("{accepted}", String(entry.accepted_source_ids?.length ?? 0));
    body.append(el("span", "source__meta", summary));

    const reasons = Array.isArray(entry.rejected_reasons)
      ? entry.rejected_reasons
      : [];
    if (reasons.length) {
      body.append(el("span", "source__meta", t("retrieval_rejections")));
      const reasonList = el("ul", "notes__list");
      for (const reason of reasons) reasonList.append(el("li", null, reason));
      body.append(reasonList);
    }
    item.append(body);
    auditList.append(item);
  }
  wrap.append(auditList);
  return wrap;
}

/* ── Sources ───────────────────────────────────────────────────────── */

function renderSources(collection) {
  const wrap = el("div", "sources");

  const groups = [
    ["academic_sources", t("group_academic")],
    ["patent_sources", t("group_patents")],
    ["market_sources", t("group_market")],
  ];

  for (const [key, title] of groups) {
    const items = collection[key] ?? [];
    if (!items.length) continue;

    wrap.append(el("h3", "sources__title", `${title} · ${items.length}`));
    const list = el("ul", "sources__list");

    for (const source of items) {
      const li = el("li", "source");

      const id = el("span", "source__id", source.source_id);
      const body = el("div", "source__body");

      const link = el("a", "source__link", source.title);
      link.href = source.url;
      link.target = "_blank";
      link.rel = "noopener noreferrer";

      const meta = el("div", "source__meta");
      const bits = [source.publisher, source.published_date?.slice(0, 4)].filter(Boolean);
      meta.append(el("span", null, bits.join(" · ")));

      const tier = el("span", "tier", source.credibility_tier);
      tier.dataset.tier = source.credibility_tier;
      meta.append(tier);

      body.append(link, meta);
      li.append(id, body);
      list.append(li);
    }
    wrap.append(list);
  }
  return wrap;
}

/* ── Narrow, non-blocking report-delivery audit ────────────────────────
 * Findings expose inspectable excerpts; an unavailable audit is not a pass. */
export function renderReportAudit(data) {
  const wrap = el("div", "consistency");
  wrap.append(el("p", "grounding__lede", t("report_audit_lede")));
  const findings = data.findings ?? [];
  if (!findings.length) {
    const message = ["failed", "unavailable"].includes(data.status)
      ? t("report_audit_unavailable")
      : t("report_audit_clear");
    wrap.append(el("p", "consistency__clear", message));
    return wrap;
  }

  const list = el("ul", "consistency__list");
  for (const finding of findings) {
    const item = el("li", "consistency__item consistency__item--warning");
    const label = finding.check === "decision_threshold_provenance"
      ? t("report_audit_threshold_finding")
      : t("report_audit_material_finding");
    item.append(el("p", "consistency__detail", label));
    if (finding.excerpt) {
      const quote = el("blockquote", "consistency__excerpt");
      quote.append(
        el("span", "consistency__excerpt-label", t("consistency_excerpt")),
        el("q", null, finding.excerpt),
      );
      item.append(quote);
    }
    list.append(item);
  }
  wrap.append(list);
  return wrap;
}
/* ── Report vs scorecard ───────────────────────────────────────────────
 * A report can urge moving quickly to market beside a scorecard reading 40,
 * and until this check existed nothing in the pipeline compared them: the
 * reviewer never sees the scorecard, the scorer never sees the reviewed
 * report. Each output is internally consistent, so every other guardrail
 * passes.
 */
export function renderConsistency(data) {
  const wrap = el("div", "consistency");
  wrap.append(el("p", "grounding__lede", t("consistency_lede")));

  const findings = data.findings ?? [];
  if (!findings.length) {
    wrap.append(el("p", "consistency__clear", t("consistency_clear")));
    return wrap;
  }

  const list = el("ul", "consistency__list");
  for (const finding of findings) {
    const item = el("li", `consistency__item consistency__item--${finding.severity}`);
    item.append(el("p", "consistency__detail", finding.detail));
    if (finding.excerpt) {
      // Quoted, not paraphrased. The whole value of the finding is that a
      // reader can go and judge the sentence for themselves rather than
      // taking a phrase table's word for it.
      const quote = el("blockquote", "consistency__excerpt");
      quote.append(el("span", "consistency__excerpt-label", t("consistency_excerpt")));
      quote.append(el("q", null, finding.excerpt));
      item.append(quote);
    }
    list.append(item);
  }
  wrap.append(list);
  return wrap;
}

/* ── Automated checks ──────────────────────────────────────────────────
 * One panel over every check the run already performed, placed above the
 * scorecard. Each of these numbers was being written to disk and returned by
 * the API, and none of them was on screen — a reader had to know they existed
 * and go and fetch the JSON.
 *
 * Split into a pure function and a renderer so what it decides — which
 * findings outrank which, and what silence is allowed to mean — is testable
 * without a DOM.
 */
// "Not checked" is less severe than a finding, but it still outranks a pass.
// Starting the reduction at ok matters: using muted as both the unknown state
// and the initial value makes either all-clean rows or all-unchecked rows win
// for the wrong reason when the ordering changes.
const _TONE_RANK = { risk: 3, warn: 2, muted: 1, ok: 0 };

/**
 * Rows for the automated-check panel, from a run's status payload.
 *
 * Returns [] when the run produced no check at all, so the caller can leave
 * the panel out entirely rather than showing an empty box that reads as
 * "checked, nothing found".
 */
export function reliabilityRows(progress) {
  const rows = [];

  const consistency = progress.consistency;
  if (consistency == null) {
    // Distinct from "consistent". The check reads English conclusions, so a
    // Chinese or Japanese report simply is not covered — and reporting that
    // as a pass would be the exact overclaim this panel exists to prevent.
    rows.push({ id: "consistency", tone: "muted",
                label: t("rel_consistency"), detail: t("rel_consistency_unchecked") });
  } else if (consistency.blockers > 0) {
    rows.push({ id: "consistency", tone: "risk", label: t("rel_consistency"),
                detail: t("rel_consistency_conflict").replace("{count}", consistency.blockers) });
  } else {
    rows.push({ id: "consistency", tone: "ok",
                label: t("rel_consistency"), detail: t("rel_consistency_ok") });
  }
  const review = progress.quality_review;
  if (review?.status === "fallback") {
    rows.push({ id: "review", tone: "warn", label: t("rel_review"),
                detail: t("rel_review_fallback") });
  } else if (review?.status === "partial") {
    rows.push({ id: "review", tone: "warn", label: t("rel_review"),
                detail: t("rel_review_partial")
                  .replace("{count}", review.unapplied_corrections ?? 0) });
  } else if (review?.status === "passed") {
    rows.push({ id: "review", tone: "ok", label: t("rel_review"),
                detail: t("rel_review_passed") });
  } else if (review?.status === "unavailable" || progress.source_counts) {
    // Runs produced before this field existed did not record whether the
    // reviewer completed. Absence cannot be upgraded to a historical pass.
    rows.push({ id: "review", tone: "muted", label: t("rel_review"),
                detail: t("rel_review_unknown") });
  }

  const grounding = progress.claim_grounding;
  if (grounding != null) {
    const status = grounding.status;
    const ungrounded = grounding.ungrounded ?? 0;
    const checked = grounding.checked ?? 0;
    const unverifiable = grounding.unverifiable ?? 0;
    const unavailableDomains = grounding.unavailable_domains ?? [];
    if (status === "failed" || status === "unavailable") {
      rows.push({ id: "grounding", tone: "muted", label: t("rel_grounding"),
                  detail: t("rel_grounding_unavailable") });
    } else if (status === "not_applicable") {
      rows.push({ id: "grounding", tone: "muted",
                  label: t("rel_grounding"), detail: t("rel_grounding_not_applicable") });
    } else if (ungrounded > 0) {
      rows.push({ id: "grounding", tone: "warn", label: t("rel_grounding"),
                  detail: t("rel_grounding_flagged").replace("{count}", ungrounded) });
    } else if (status === "partial") {
      rows.push({ id: "grounding", tone: "muted", label: t("rel_grounding"),
                  detail: t("rel_grounding_degraded")
                    .replace("{domains}", unavailableDomains.join(", ")) });
    } else if (checked === 0) {
      // Zero unsupported out of zero checked. Shown as "nothing could be
      // checked" rather than as a clean result, because the two are opposite
      // statements that produce the same pair of numbers.
      rows.push({ id: "grounding", tone: "muted",
                  label: t("rel_grounding"), detail: t("rel_grounding_none") });
    } else if (unverifiable > 0) {
      // Some matches do not make the unchecked remainder disappear. Calling
      // this a pass was the same silence-as-success bug in a less obvious shape.
      rows.push({ id: "grounding", tone: "muted", label: t("rel_grounding"),
                  detail: t("rel_grounding_partial")
                    .replace("{checked}", checked)
                    .replace("{unverifiable}", unverifiable) });
    } else {
      rows.push({ id: "grounding", tone: "ok", label: t("rel_grounding"),
                  detail: t("rel_grounding_ok").replace("{count}", checked) });
    }
  } else if (progress.source_counts) {
    rows.push({ id: "grounding", tone: "muted", label: t("rel_grounding"),
                detail: t("rel_grounding_unknown") });
  }

  const failed = progress.failed_domains ?? [];
  const reportAudit = progress.report_audit;
  if (reportAudit == null && progress.source_counts) {
    rows.push({ id: "report-audit", tone: "muted", label: t("rel_report_audit"),
                detail: t("rel_report_audit_unknown") });
  } else if (["failed", "unavailable"].includes(reportAudit?.status)) {
    rows.push({ id: "report-audit", tone: "muted", label: t("rel_report_audit"),
                detail: t("rel_report_audit_unavailable") });
  } else if ((reportAudit?.findings ?? 0) > 0) {
    rows.push({ id: "report-audit", tone: "warn", label: t("rel_report_audit"),
                detail: t("rel_report_audit_flagged").replace("{count}", reportAudit.findings) });
  } else if (reportAudit?.status === "partial") {
    rows.push({ id: "report-audit", tone: "muted", label: t("rel_report_audit"),
                detail: t("rel_report_audit_partial")
                  .replace("{checked}", reportAudit.citation_scope_checked ?? 0)
                  .replace("{unverifiable}", reportAudit.citation_scope_unverifiable ?? 0) });
  } else if (reportAudit?.status === "not_applicable") {
    rows.push({ id: "report-audit", tone: "muted", label: t("rel_report_audit"),
                detail: t("rel_report_audit_not_applicable") });
  } else if (reportAudit?.status === "completed") {
    rows.push({ id: "report-audit", tone: "ok", label: t("rel_report_audit"),
                detail: t("rel_report_audit_clear")
                  .replace("{count}", reportAudit.citation_scope_checked ?? 0) });
  }

  if (failed.length) {
    rows.push({ id: "sources", tone: "warn", label: t("rel_sources"),
                detail: t("rel_sources_failed").replace("{domains}", failed.join(", ")) });
  } else if (progress.source_counts) {
    rows.push({ id: "sources", tone: "ok",
                label: t("rel_sources"), detail: t("rel_sources_ok") });
  }
  const authority = progress.authority_coverage;
  if (authority?.status === "incomplete") {
    const missing = (authority.missing_categories ?? []).map(
      category => t("authority_" + category),
    ).join(", ");
    rows.push({ id: "authority", tone: "warn", label: t("rel_authority"),
                detail: t("rel_authority_missing").replace("{categories}", missing) });
  } else if (authority?.status === "complete") {
    rows.push({ id: "authority", tone: "ok", label: t("rel_authority"),
                detail: t("rel_authority_complete") });
  } else if (authority == null && progress.source_counts) {
    // Old runs have no field. Absence says the check did not exist, not that
    // every required authority category was covered.
    rows.push({ id: "authority", tone: "muted", label: t("rel_authority"),
                detail: t("rel_authority_unchecked") });
  }
  const components = progress.component_coverage;
  if (components?.status === "incomplete") {
    const missing = (components.missing_components ?? []).join(", ");
    let detail = t("rel_components_missing").replace("{components}", missing);
    const unchecked = (components.unchecked_components ?? []).join(", ");
    if (unchecked) {
      detail += " " + t("rel_components_unchecked")
        .replace("{components}", unchecked);
    }
    rows.push({ id: "components", tone: "warn", label: t("rel_components"),
                detail });
  } else if (components?.status === "complete") {
    rows.push({ id: "components", tone: "ok", label: t("rel_components"),
                detail: t("rel_components_complete") });
  } else if (["partial", "unchecked"].includes(components?.status)) {
    const unchecked = (components.unchecked_components ?? []).join(", ");
    rows.push({ id: "components", tone: "muted", label: t("rel_components"),
                detail: t("rel_components_unchecked")
                  .replace("{components}", unchecked) });
  }


  if (progress.evidence_incomplete) {
    rows.push({ id: "trail", tone: "warn",
                label: t("rel_trail"), detail: t("rel_trail_incomplete") });
  }

  // The API isolates malformed summaries instead of failing the paid report.
  // Its safe null/[]/false replacements are NOT measurements. Override the
  // affected row after ordinary rendering so defaults cannot turn a read
  // fault into either a pass or a historically absent check. Names/labels are
  // code-owned; never echo damaged payloads into the diagnostic.
  const faultRows = {
    consistency: ["consistency", "rel_consistency"],
    quality_review: ["review", "rel_review"],
    claim_grounding: ["grounding", "rel_grounding"],
    report_audit: ["report-audit", "rel_report_audit"],
    authority_coverage: ["authority", "rel_authority"],
    component_coverage: ["components", "rel_components"],
    source_counts: ["sources", "rel_sources"],
    failed_domains: ["sources", "rel_sources"],
    evidence_incomplete: ["trail", "rel_trail"],
  };
  for (const field of progress.audit_metadata_unreadable ?? []) {
    if (!Object.hasOwn(faultRows, field)) continue;
    const [id, label] = faultRows[field];
    const row = { id, tone: "muted", label: t(label), detail: t("rel_metadata_unreadable") };
    const index = rows.findIndex(existing => existing.id === id);
    if (index === -1) rows.push(row);
    else if (["warn", "risk"].includes(rows[index].tone)) {
      // Source counts and failed_domains share a row. A damaged count must
      // not erase a separately readable retrieval failure in that same row.
      rows[index] = { ...rows[index], detail: rows[index].detail + " " + row.detail };
    }
    else rows[index] = row;
  }

  return rows;
}

/** The panel's headline, from the worst row present. */
export function reliabilityVerdict(rows) {
  if (!rows.length) return { tone: "muted", label: t("rel_verdict_unknown") };
  const worst = rows.reduce(
    (acc, row) => (_TONE_RANK[row.tone] > _TONE_RANK[acc] ? row.tone : acc), "ok");
  if (worst === "risk") return { tone: "risk", label: t("rel_verdict_risk") };
  if (worst === "warn") return { tone: "warn", label: t("rel_verdict_review") };
  if (worst === "ok") {
    return { tone: "ok", label: t("rel_verdict_clear"), note: t("rel_verdict_clear_sub") };
  }
  return { tone: "muted", label: t("rel_verdict_unknown") };
}

export function renderReliability(progress) {
  const rows = reliabilityRows(progress);
  if (!rows.length) return null;

  const verdict = reliabilityVerdict(rows);
  const wrap = el("section", "reliability");
  wrap.dataset.tone = verdict.tone;

  const head = el("div", "reliability__head");
  head.append(el("span", "reliability__title", t("rel_title")));
  head.append(el("strong", "reliability__verdict", verdict.label));
  wrap.append(head);

  if (verdict.note) wrap.append(el("p", "reliability__note", verdict.note));

  const list = el("ul", "reliability__rows");
  for (const row of rows) {
    const item = el("li", "reliability__row");
    item.dataset.tone = row.tone;
    item.dataset.check = row.id;
    item.append(el("span", "reliability__label", row.label));
    item.append(el("span", "reliability__detail", row.detail));
    list.append(item);
  }
  wrap.append(list);
  return wrap;
}
