/* ── Reader feedback ───────────────────────────────────────────────────
 * One click under the tabs: did the report change how the reader sees the
 * decision, and which part mattered. A closed vocabulary and no text, kept
 * with the run for the operator's ops report. Nobody else's answer is shown.
 */
const FEEDBACK_ANSWERS = ["yes", "no", "unsure"];
const FEEDBACK_PARTS = ["scorecard", "report", "sources", "checks"];

/**
 * The feedback block for one recorded state. `onAnswer(changed_view, part)`
 * runs on a click. Pure in the state, so it can be asserted on without a
 * network; the mount below fetches, renders, and re-renders on each reply.
 */
export function feedbackView(state, onAnswer = () => {}) {
  const recorded = Boolean(state?.recorded);
  const wrap = el("section", "feedback");
  wrap.dataset.recorded = String(recorded);
  wrap.append(el("h4", "feedback__title", t("feedback_title")));

  const choices = el("div", "feedback__choices");
  for (const answer of FEEDBACK_ANSWERS) {
    const button = el("button", "btn btn--secondary feedback__answer", t("feedback_" + answer));
    button.type = "button";
    button.dataset.answer = answer;
    button.setAttribute("aria-pressed", String(state?.changed_view === answer));
    button.addEventListener("click", () => onAnswer(answer, state?.part ?? null));
    choices.append(button);
  }
  wrap.append(choices);

  // The part question follows an answer; asked first it reads as a form.
  const parts = el("div", "feedback__parts");
  parts.hidden = !recorded;
  parts.append(el("span", "feedback__parts-label", t("feedback_part_title")));
  for (const part of FEEDBACK_PARTS) {
    const button = el("button", "btn btn--secondary feedback__part", t("feedback_part_" + part));
    button.type = "button";
    button.dataset.part = part;
    button.setAttribute("aria-pressed", String(state?.part === part));
    button.addEventListener("click", () => onAnswer(state.changed_view, part));
    parts.append(button);
  }
  wrap.append(parts);

  const status = el("p", "feedback__status");
  if (state?.failed) status.textContent = t("feedback_failed");
  else if (recorded) status.textContent = `${t("feedback_recorded")} ${t("feedback_change")}`;
  else status.textContent = t("feedback_note");
  wrap.append(status);
  return wrap;
}

function renderFeedback(container, runId) {
  let node = null;
  let current = { recorded: false };
  const paint = (state) => {
    current = state;
    const next = feedbackView(state, submit);
    if (node) node.replaceWith(next); else container.append(next);
    node = next;
  };
  async function submit(changed_view, part) {
    for (const button of node.querySelectorAll("button")) button.disabled = true;
    try {
      paint(await api.sendFeedback(runId, { changed_view, part }));
    } catch {
      // Keep what was recorded; the failed save is the one fact to add.
      paint({ ...current, failed: true });
    }
  }
  // A reader who cannot answer (a shared link to a code-owned run, or a
  // deployment fault) gets no block at all rather than a broken control.
  api.getFeedback(runId).then(paint).catch(() => {});
}

export async function render(container, runId, progress) {
  container.innerHTML = "";
  const artifacts = progress.artifacts ?? [];

  const tabs = el("div", "tabs");
  const panels = el("div", "panels");

  const views = [];
  if (artifacts.includes("scores")) views.push({ id: "score", label: t("tab_score") });
  if (artifacts.includes("report")) views.push({ id: "report", label: t("tab_report") });
  if (artifacts.includes("sources")) views.push({ id: "sources", label: t("tab_sources") });
  if (artifacts.includes("grounding"))
    views.push({ id: "grounding", label: t("tab_grounding") });
  if (artifacts.includes("consistency"))
    views.push({ id: "consistency", label: t("tab_consistency") });
  if (artifacts.includes("retrieval"))
    views.push({ id: "retrieval", label: t("tab_retrieval") });
  if (artifacts.includes("report-audit"))
    views.push({ id: "report-audit", label: t("tab_report_audit") });

  if (!artifacts.includes("sources")) {
    container.append(el("p", "empty-note sources__missing", t("sources_missing_artifact")));
  }

  if (!views.length) {
    container.append(el("p", "empty-note", t("no_artifacts")));
    return;
  }

  // Above the tabs, not inside one. Every finding it summarises was already
  // being computed and written to disk, and every one of them qualifies the
  // score — so a reader has to meet them before the number, not after
  // choosing to go looking in a tab.
  const reliability = renderReliability(progress);
  const applicability = renderDecisionApplicability(progress.decision_gate);
  if (applicability) container.append(applicability);
  // The brief needs the scorecard, the report and the sources; it fills in
  // below once they arrive, and a run without a scorecard has none.
  const briefSlot = progress.state === "completed" && artifacts.includes("scores") ? el("div", "brief-slot") : null;
  if (briefSlot) container.append(briefSlot);
  if (reliability) container.append(reliability);

  for (const view of views) {
    const tab = el("button", "tab", view.label);
    tab.type = "button";
    tab.dataset.view = view.id;
    tab.addEventListener("click", () => select(view.id));
    tabs.append(tab);

    const panel = el("div", "panel");
    panel.dataset.view = view.id;
    panel.hidden = true;
    panels.append(panel);
  }

  container.append(tabs, panels);

  // Under the tabs, for a delivered report only. Mounted after the panels
  // so a slow or refused feedback read never delays the report itself.
  if (progress.state === "completed") renderFeedback(container, runId);

  const loaded = new Set();
  // One request each, shared by the tabs and the citation cards.
  let scoresRequest = null;
  let indexRequest = null;
  const scoresOnce = () => (scoresRequest ??= api.getArtifact(runId, "scores"));
  let reportRequest = null;
  const reportOnce = () => (reportRequest ??= api.getReport(runId));
  const indexOnce = () => (indexRequest ??= reportOnce().then(citationIndex));
  const hasSources = artifacts.includes("sources");
  let sourcesRequest = null;
  const sourcesOnce = () => (sourcesRequest ??= api.getArtifact(runId, "sources"));

  if (briefSlot) {
    // A failed report or sources read costs the brief a line, never the brief;
    // a failed scorecard read removes the slot, since there is nothing to say.
    Promise.all([scoresOnce(), reportOnce().catch(() => ""), hasSources ? sourcesOnce().catch(() => null) : null])
      .then(([scores, markdown, sources]) => {
        const data = decisionBrief({ scores, markdown, sources, progress });
        if (!data) { briefSlot.remove(); return; }
        const node = renderDecisionBrief(data);
        briefSlot.replaceWith(node);
        attachCitations(node, indexOnce, { onShowInSources: hasSources ? showInSources : null });
      })
      .catch(() => briefSlot.remove());
  }

  async function showInSources(id) {
    await select("sources");
    const search = panels.querySelector('[data-view="sources"] .sources__search');
    if (!search) return;
    search.value = id;
    search.dispatchEvent(new Event("input"));
  }

  async function select(id) {
    for (const tab of tabs.children) tab.dataset.active = String(tab.dataset.view === id);
    for (const panel of panels.children) panel.hidden = panel.dataset.view !== id;

    if (loaded.has(id)) return;
    loaded.add(id);

    const panel = panels.querySelector(`[data-view="${id}"]`);
    panel.append(el("div", "skeleton", ""));

    try {
      if (id === "score") {
        // The market figures come from the sources artifact; a refused or
        // failed read leaves the scorecard without them, never without itself.
        const [scores, sources] = await Promise.all([
          scoresOnce(), hasSources ? sourcesOnce().catch(() => null) : null]);
        panel.innerHTML = "";
        panel.append(renderScorecard(scores, sources));
        attachCitations(panel, indexOnce, { onShowInSources: hasSources ? showInSources : null });
      } else if (id === "report") {
        const md = await reportOnce();
        indexRequest ??= Promise.resolve(citationIndex(md));
        // The score comes from the last agent, after the report was written,
        // so the report cannot state it; the reader still meets it here.
        const scores = artifacts.includes("scores") ? await scoresOnce().catch(() => null) : null;
        panel.innerHTML = "";
        const line = renderReportScoreLine(scores, () => select("score"));
        if (line) panel.append(line);
        const article = el("article", "prose");
        article.innerHTML = renderMarkdown(md);
        panel.append(article);
        attachCitations(article, indexOnce, { onShowInSources: hasSources ? showInSources : null });
      } else if (id === "grounding") {
        const grounding = await api.getArtifact(runId, "grounding");
        panel.innerHTML = "";
        panel.append(renderGrounding(grounding));
      } else if (id === "consistency") {
        const consistency = await api.getArtifact(runId, "consistency");
        panel.innerHTML = "";
        panel.append(renderConsistency(consistency));
      } else if (id === "retrieval") {
        const diagnostics = await api.getArtifact(runId, "retrieval");
        panel.innerHTML = "";
        panel.append(renderRetrievalDiagnostics(diagnostics));
      } else if (id === "report-audit") {
        const audit = await api.getArtifact(runId, "report-audit");
        panel.innerHTML = "";
        panel.append(renderReportAudit(audit));
      } else {
        const sources = await sourcesOnce();
        panel.innerHTML = "";
        panel.append(renderSources(sources));
      }
    } catch (err) {
      panel.innerHTML = "";
      if (id === "sources") {
        sourcesRequest = null;  // let a retry re-fetch
        // Saved private text may occur in server, parser or network messages.
        // A failed read is not an empty registry; never echo its raw message.
        const message = err?.status === 409 ? "sources_unavailable"
          : err?.status === 404 ? "sources_resource_unavailable" : "sources_read_failed";
        panel.append(el("p", "empty-note sources__error", t(message)));
      } else {
        panel.append(el("p", "empty-note", err.message));
      }
      loaded.delete(id);      // let a retry re-fetch
    }
  }

  select(views[0].id);
}

/* ── Citation check ────────────────────────────────────────────────────
 * What the server could and could not verify about the report's numbers.
 *
 * The counts are shown together on purpose. "0 unsupported" alone reads as a
 * clean bill of health, when next to a large "could not check" it means the
 * screen mostly did not run — a different statement, and the one a reader
 * needs in order to know how much the first number is worth.
 */

// Exported for the same reason renderMarkdown is: the app calls it only
// through render(), but what it decides — how three counts are presented
// relative to each other — is worth asserting on directly.
export function renderGrounding(data) {
  const wrap = el("div", "grounding");
  if (!detailRecord(data) || !["checked", "ungrounded", "unverifiable"].every(key => detailCount(data[key]))
      || data.ungrounded > data.checked) {
    wrap.append(detailUnavailable()); return wrap;
  }
  const { checked, ungrounded, unverifiable } = data;

  wrap.append(el("p", "grounding__lede", t("grounding_lede")));
  // Zero checked is not evidence of a successful screen, including valid
  // all-zero historical artifacts. Do not infer full report verification.
  if (data.error || checked === 0) wrap.append(el("p", "empty-note", t("detail_not_checked")));

  const stats = el("div", "grounding__stats");
  for (const [value, label, tone] of [
    [checked, t("grounding_checked"), checked && !data.error ? "ok" : "muted"],
    [ungrounded, t("grounding_ungrounded"), ungrounded ? "warn" : checked && !data.error ? "ok" : "muted"],
    [unverifiable, t("grounding_unverifiable"), "muted"],
  ]) {
    const cell = el("div", `grounding__stat grounding__stat--${tone}`);
    cell.append(el("div", "grounding__value", String(value)));
    cell.append(el("div", "grounding__label", label));
    stats.append(cell);
  }
  wrap.append(stats);

  const duplicatesCollapsed = data.duplicates_collapsed ?? 0;
  if (!detailCount(duplicatesCollapsed)) wrap.append(detailUnavailable());
  else if (duplicatesCollapsed > 0) {
    const note = t("grounding_duplicates").replace(
      "{count}", String(duplicatesCollapsed),
    );
    wrap.append(el("p", "grounding__lede", note));
  }

  // Per domain, because one aggregate cannot say both "the check works" and
  // "market reports have no abstract to check against".
  const byDomain = data.by_domain ?? {};
  if (data.by_domain !== undefined && !detailRecord(data.by_domain)) wrap.append(detailUnavailable());
  const domains = [
    ["academic", t("group_academic")],
    ["patent", t("group_patents")],
    ["market", t("group_market")],
  ].filter(([key]) => byDomain[key]);

  if (domains.length) {
    const list = el("ul", "grounding__domains");
    for (const [key, label] of domains) {
      const d = byDomain[key];
      if (!detailRecord(d) || !["checked", "ungrounded", "unverifiable"].every(k => detailCount(d[k]))
          || d.ungrounded > d.checked) {
        list.append(el("li", "grounding__domain", `${label}: ${t("detail_unreadable")}`));
        continue;
      }
      const total = d.checked + d.unverifiable;
      const text = total
        ? `${label}: ${d.checked}/${total} ${t("grounding_checkable")}`
        : `${label}: ${t("grounding_no_figures")}`;
      list.append(el("li", "grounding__domain", text));
    }
    wrap.append(list);
  }

  const rows = data.findings;
  if (!Array.isArray(rows)) { wrap.append(detailUnavailable()); return wrap; }
  if (!rows.length) return wrap;

  const list = el("ul", "grounding__list");
  for (const row of rows) {
    if (!detailRecord(row) || typeof row.finding_id !== "string"
        || !["grounded", "ungrounded", "unverifiable"].includes(row.status)
        || (row.claim !== undefined && typeof row.claim !== "string")
        || (row.ungrounded_figures !== undefined && !detailStrings(row.ungrounded_figures))
        || (row.unverifiable_reason != null && typeof row.unverifiable_reason !== "string")) {
      list.append(detailUnavailable()); continue;
    }
    const item = el("li", `grounding__item grounding__item--${row.status}`);
    item.append(el("span", "grounding__id", `${row.finding_id}`));
    item.append(el("span", "grounding__claim", row.claim ?? ""));
    const why = row.status === "ungrounded"
      ? t("grounding_missing").replace("{figures}",
          (row.ungrounded_figures ?? []).join(", "))
      : row.unverifiable_reason ?? "";
    if (why) item.append(el("span", "grounding__why", why));
    list.append(item);
  }
  wrap.append(el("h3", "sources__title", t("grounding_detail")));
  wrap.append(list);
  return wrap;
}

/* ── Failed retrieval diagnostics ─────────────────────────────────────
 * A failed pre-agent run has no validated_sources.json, so this is the only
 * durable explanation of what the search layer understood and rejected.
 * Every third-party string is assigned through textContent via el(); none of
 * the audit data is trusted as HTML.
 */
export function renderRetrievalDiagnostics(data) {
  const wrap = el("div", "sources");
  wrap.append(el("p", "grounding__lede", t("retrieval_lede")));

  const accepted = Number(data.accepted_sources ?? 0);
  const required = Number(data.required_sources ?? 0);
  const count = t("retrieval_count")
    .replace("{accepted}", String(accepted))
    .replace("{required}", String(required));
  wrap.append(el("p", "consistency__clear", count));

  const aliases = Array.isArray(data.aliases) && data.aliases.length
    ? data.aliases.join(" · ")
    : "—";
  const fields = [
    [t("retrieval_input"), data.input_topic || "—"],
    [t("retrieval_search"), data.search_topic || "—"],
    [t("retrieval_aliases"), aliases],
  ];
  const plan = el("ul", "sources__list");
  for (const [label, value] of fields) {
    const row = el("li", "source");
    row.append(
      el("span", "source__id", label),
      el("span", "source__body", value),
    );
    plan.append(row);
  }
  wrap.append(plan, el("h3", "sources__title", t("retrieval_audit")));

  const audit = Array.isArray(data.audit) ? data.audit : [];
  if (!audit.length) {
    wrap.append(el("p", "empty-note", t("retrieval_no_audit")));
    return wrap;
  }

  const auditList = el("ul", "sources__list");
  for (const entry of audit) {
    const item = el("li", "source");
    const body = el("div", "source__body");
    body.append(el("span", "source__link", entry.query || "—"));
    const summary = t("retrieval_query_summary")
      .replace("{domain}", entry.domain || "academic")
      .replace("{results}", String(entry.result_count ?? 0))
      .replace("{accepted}", String(entry.accepted_source_ids?.length ?? 0));
    body.append(el("span", "source__meta", summary));

    const reasons = Array.isArray(entry.rejected_reasons)
      ? entry.rejected_reasons
      : [];
    if (reasons.length) {
      body.append(el("span", "source__meta", t("retrieval_rejections")));
      const reasonList = el("ul", "notes__list");
      for (const reason of reasons) reasonList.append(el("li", null, reason));
      body.append(reasonList);
    }
    item.append(body);
    auditList.append(item);
  }
  wrap.append(auditList);
  return wrap;
}

/* ── Sources ───────────────────────────────────────────────────────── */

const SOURCE_GROUPS = [
  ["academic_sources", "group_academic"],
  ["patent_sources", "group_patents"],
  ["market_sources", "group_market"],
];
const SOURCE_ROW_LIMIT = 1000;
const SOURCE_STRING_LIMIT = 16384;
const SOURCE_TOTAL_LIMIT = 2 * 1024 * 1024;
const SOURCE_PAGE_SIZE = 50;

function savedSourceUrl(value) {
  // No base URL: a relative or scheme-relative link must remain plain text.
  // Reject controls before URL parsing, which would silently remove some.
  if (!/^https?:\/\//i.test(value) || /[\u0000-\u0020\u007f-\u009f]/u.test(value)) return null;
  try {
    const url = new URL(value);
    return ["http:", "https:"].includes(url.protocol) && url.hostname && !url.username && !url.password
      ? url.href : null;
  } catch {
    return null;
  }
}

function admitSavedSources(collection) {
  const admitted = { rows: [], partial: false, empty: false };
  if (!detailRecord(collection)) { admitted.partial = true; return admitted; }
  admitted.empty = SOURCE_GROUPS.every(([key]) => Array.isArray(collection[key]) && collection[key].length === 0);
  let inspected = 0;
  let units = 0;

  // These are after-JSON display/search bounds, not HTTP or JSON-parser bounds.
  // Count inspected rows (even malformed ones) and only examine a fixed field
  // whitelist. Never enumerate arbitrary metadata or scan an unbounded tail.
  for (const [group] of SOURCE_GROUPS) {
    const items = collection[group];
    if (!Array.isArray(items)) { admitted.partial = true; continue; }
    const count = Math.min(items.length, SOURCE_ROW_LIMIT - inspected);
    if (count < items.length) admitted.partial = true;
    for (let index = 0; index < count; index++) {
      inspected++;
      const raw = items[index];
      if (!detailRecord(raw)) { admitted.partial = true; continue; }
      const row = { group, invalid: false };
      const unreadable = state => {
        admitted.partial = true;
        row.invalid = true;
        return { text: null, state };
      };
      const field = (key, required = false) => {
        const value = raw[key];
        if (value == null && !required) return { text: null, state: "missing" };
        if (typeof value !== "string") return unreadable("invalid");
        // Check lengths before copying, lowercasing, URL parsing or DOM work.
        // Reject whole fields, never present a truncated excerpt as original.
        if (value.length > SOURCE_STRING_LIMIT || value.length > SOURCE_TOTAL_LIMIT - units) {
          return unreadable("limited");
        }
        units += value.length;
        if (required && !value.trim()) return unreadable("invalid");
        // Whitespace-only excerpts still keep every original character, but
        // must not be presented as containing readable saved evidence.
        return { text: value, state: value.trim().length ? "available" : "empty" };
      };
      row.source_id = field("source_id", true);
      row.title = field("title", true);
      for (const key of ["publisher", "published_date", "accessed_date", "credibility_tier", "url",
                         "evidence_summary", "summary_source"]) {
        row[key] = field(key);
      }
      row.href = row.url.text ? savedSourceUrl(row.url.text) : null;
      if (row.url.text && !row.href) unreadable("invalid");
      row.searchId = row.source_id.text?.toLowerCase() ?? null;
      // Keep field boundaries: a title suffix plus publisher prefix is not a
      // match in either saved field. IDs are handled separately and exactly.
      row.searchFields = [row.title.text, row.publisher.text, row.evidence_summary.text]
        .filter(value => value !== null).map(value => value.toLowerCase());
      admitted.rows.push(row);
    }
  }
  return admitted;
}

function renderSavedSource(source) {
  const li = el("li", "source");
  const id = el("span", "source__id", source.source_id.text ?? t("sources_id_unavailable"));
  const body = el("div", "source__body");
  const title = el(source.href ? "a" : "span", "source__link", source.title.text ?? t("sources_title_unavailable"));
  if (source.href) {
    title.href = source.href;
    title.target = "_blank";
    title.rel = "noopener noreferrer";
  }
  const meta = el("div", "source__meta");
  const bits = [source.publisher.text, source.published_date.text?.slice(0, 4)].filter(Boolean);
  meta.append(el("span", null, bits.join(" · ")));
  if (source.credibility_tier.text) {
    const tier = el("span", "tier", source.credibility_tier.text);
    if (["high", "medium", "low"].includes(source.credibility_tier.text)) {
      tier.dataset.tier = source.credibility_tier.text;
    }
    meta.append(tier);
  }
  const age = marketSourceAge(source.source_id.text, source.published_date.text, source.accessed_date.text);
  if (age) meta.append(el("span", "source__age", ageText(age)));
  body.append(title, meta);
  if (source.invalid) body.append(el("p", "source__fault", t("sources_record_partial")));

  const excerpt = el("details", "source__excerpt");
  excerpt.append(el("summary", null, t("sources_excerpt")));
  const label = source.summary_source.text;
  const labelKey = ["abstract", "search_snippet"].includes(label)
    ? "sources_summary_source" : "sources_summary_unrecognized";
  excerpt.append(el("p", "source__summary-source", label
    ? t(labelKey).replace("{label}", () => label) : t("sources_summary_unrecorded")));
  const saved = source.evidence_summary;
  if (saved.text !== null) {
    // Direct textContent, including an empty string and all original white
    // space. No Markdown, autolinks, highlighting or excerpt normalization.
    excerpt.append(el("div", "source__text", saved.text));
  }
  if (saved.state !== "available") {
    excerpt.append(el("p", "source__excerpt-state", t(`sources_excerpt_${saved.state}`)));
  }
  body.append(excerpt);
  li.append(id, body);
  return li;
}

function renderSources(collection) {
  const wrap = el("div", "sources sources--browser");
  const admitted = admitSavedSources(collection);
  wrap.append(el("p", "sources__disclosure", t("sources_disclosure")));
  if (admitted.partial) wrap.append(el("p", "sources__warning", t("sources_incomplete")));

  const controls = el("div", "sources__controls");
  const label = el("label", "sources__search-label");
  label.append(el("span", null, t("sources_search_label")));
  const search = el("input", "sources__search");
  search.type = "search";
  search.maxLength = SOURCE_STRING_LIMIT;
  search.autocomplete = "off";
  search.spellcheck = false;
  search.placeholder = t("sources_search_placeholder");
  label.append(search);
  const clear = el("button", "btn btn--secondary sources__clear", t("sources_clear"));
  clear.type = "button";
  controls.append(label, clear);
  const status = el("p", "sources__status");
  status.setAttribute("role", "status");
  status.setAttribute("aria-live", "polite");
  const results = el("div", "sources__results");
  const pager = el("div", "sources__pager");
  const previous = el("button", "btn btn--secondary sources__prev", t("sources_previous"));
  const next = el("button", "btn btn--secondary sources__next", t("sources_next"));
  previous.type = next.type = "button";
  pager.append(previous, next);
  wrap.append(controls, el("p", "sources__hint", t("sources_search_hint")), status, results, pager);

  // All view state belongs to this render. An old GET can only update its
  // detached panel; there is no shared selection, storage, URL or log state.
  let page = 0;
  let matches = admitted.rows;
  let query = "";
  const paint = () => {
    results.replaceChildren();
    const start = page * SOURCE_PAGE_SIZE;
    const visible = matches.slice(start, start + SOURCE_PAGE_SIZE);
    for (const [group, heading] of SOURCE_GROUPS) {
      const rows = visible.filter(row => row.group === group);
      if (!rows.length) continue;
      const count = matches.filter(row => row.group === group).length;
      results.append(el("h3", "sources__title", `${t(heading)} · ${count}`));
      const list = el("ul", "sources__list");
      for (const row of rows) list.append(renderSavedSource(row));
      results.append(list);
    }
    if (!matches.length) {
      const message = query ? "sources_no_match" : admitted.empty ? "sources_empty" : "sources_no_records";
      results.append(el("p", "empty-note", t(message)));
    }
    status.textContent = t("sources_count").replace("{matched}", String(matches.length))
      .replace("{total}", String(admitted.rows.length)).replace("{start}", String(matches.length ? start + 1 : 0))
      .replace("{end}", String(start + visible.length));
    clear.disabled = !search.value;
    previous.disabled = page === 0;
    next.disabled = start + SOURCE_PAGE_SIZE >= matches.length;
  };
  const filter = () => {
    query = search.value.trim().toLowerCase();
    // A fixed recognizer selects ID mode; user text never becomes a regex.
    const isId = /^(?:[apm]\d+|\[[apm]\d+\])$/.test(query);
    const id = query.startsWith("[") ? query.slice(1, -1) : query;
    matches = admitted.rows.filter(row => !query || (isId
      ? row.searchId === id : row.searchFields.some(value => value.includes(query))));
    page = 0;
    paint();
  };
  search.addEventListener("input", filter);
  clear.addEventListener("click", () => { search.value = ""; filter(); search.focus(); });
  previous.addEventListener("click", () => { if (page > 0) { page--; paint(); } });
  next.addEventListener("click", () => {
    if ((page + 1) * SOURCE_PAGE_SIZE < matches.length) { page++; paint(); }
  });
  paint();
  return wrap;
}

/* ── Narrow, non-blocking report-delivery audit ────────────────────────
 * Findings expose inspectable excerpts; an unavailable audit is not a pass. */
function auditFindingsReadable(findings) {
  return Array.isArray(findings) && findings.every(row =>
    row && typeof row === "object" && !Array.isArray(row) &&
    ["decision_threshold_provenance", "citation_material_scope"].includes(row.check) &&
    typeof row.excerpt === "string");
}

function auditSectionReadable(section, material) {
  if (!section || typeof section !== "object" || Array.isArray(section) ||
      !["completed", "partial", "not_applicable", "unavailable", "failed"].includes(section.status) ||
      !auditFindingsReadable(section.findings) ||
      (section.reason !== undefined && typeof section.reason !== "string")) return false;
  const keys = material ? ["candidate_segments", "checked", "mismatched", "unverifiable"]
    : ["candidate_lines", "unqualified"];
  if (!keys.every(key => Number.isSafeInteger(section[key]) && section[key] >= 0)) return false;
  const count = material ? section.mismatched : section.unqualified;
  const candidates = material ? section.candidate_segments : section.candidate_lines;
  const check = material ? "citation_material_scope" : "decision_threshold_provenance";
  // A valid integer is not enough: completed-with-unverifiable is internally
  // inconsistent and must not paint the section as evaluated.
  if (section.status === "not_applicable" && candidates !== 0) return false;
  if (section.status === "completed" && (candidates === 0 || (material && section.unverifiable !== 0))) return false;
  if (section.status === "partial" && (!material || section.checked === 0 || section.unverifiable === 0)) return false;
  if (["unavailable", "failed"].includes(section.status) && (material ? section.checked !== 0 : candidates !== 0)) return false;
  return count === section.findings.length && count <= candidates &&
    section.findings.every(row => row.check === check) &&
    (!material || (section.checked + section.unverifiable === candidates && count <= section.checked));
}

export function renderReportAudit(data) {
  const wrap = el("div", "consistency");
  wrap.append(el("p", "grounding__lede", t("report_audit_lede")));
  // The artifact endpoint preserves stored bytes. `{}.length` must not become
  // "no findings", and a null row must not throw away a paid report's panel.
  // This validates display shapes, not storage or semantic source truth.
  if (!data || data.schema_version !== 1 || data.non_blocking !== true ||
      !["completed", "partial", "not_applicable", "unavailable", "failed"].includes(data.status) ||
      !auditFindingsReadable(data.findings) || data.findings_count !== data.findings.length) {
    wrap.append(el("p", "empty-note", t("report_audit_unreadable")));
    return wrap;
  }

  let sectionsReadable = true;
  for (const [key, material] of [["decision_thresholds", false], ["citation_material_scope", true]]) {
    const section = data[key];
    const detail = el("div", "audit-section");
    detail.dataset.check = key;
    detail.append(el("h3", null, t(material ? "report_audit_material_title" : "report_audit_threshold_title")));
    // Isolate a malformed section, not its healthy neighbour. Missing
    // historical detail is unknown; never synthesize zero coverage for it.
    if (!auditSectionReadable(section, material)) {
      sectionsReadable = false;
      detail.append(el("p", "empty-note", t("report_audit_unreadable")));
    } else {
      const statusKey = ["failed", "unavailable"].includes(section.status) ? "unavailable" : section.status;
      detail.append(el("p", null, t(`report_audit_state_${statusKey}`)));
      const coverage = material
        ? t("report_audit_material_counts").replace("{candidates}", section.candidate_segments)
            .replace("{checked}", section.checked).replace("{unverifiable}", section.unverifiable)
        : t("report_audit_threshold_counts").replace("{candidates}", section.candidate_lines)
            .replace("{unqualified}", section.unqualified);
      detail.append(el("p", null, coverage));
      if (section.reason) {
        // textContent, including for future reason codes, never artifact HTML.
        const reason = section.reason === "unsupported_report_language"
          ? t("report_audit_language_unsupported") : section.reason;
        detail.append(el("p", null, t("report_audit_reason").replace("{reason}", reason)));
      }
    }
    wrap.append(detail);
  }
  const findings = data.findings;
  if (!findings.length) {
    // Intact top-level status cannot vouch for unreadable nested counters.
    const hasIncompleteSection = [data.decision_thresholds, data.citation_material_scope]
      .some(section => section && ["partial", "unavailable", "failed"].includes(section.status));
    const noCandidates = [data.decision_thresholds, data.citation_material_scope]
      .every(section => section && section.status === "not_applicable");
    const message = !sectionsReadable ? "report_audit_unreadable"
      : ["failed", "unavailable"].includes(data.status) ? "report_audit_unavailable"
        : data.status === "partial" || hasIncompleteSection ? "report_audit_state_partial"
          : data.status === "not_applicable" || noCandidates ? "report_audit_state_not_applicable" : "report_audit_clear";
    wrap.append(el("p", "empty-note", t(message)));
    return wrap;
  }

  const list = el("ul", "consistency__list");
  for (const finding of findings) {
    const item = el("li", "consistency__item consistency__item--warning");
    const label = finding.check === "decision_threshold_provenance"
      ? t("report_audit_threshold_finding")
      : t("report_audit_material_finding");
    item.append(el("p", "consistency__detail", label));
    if (finding.excerpt) {
      const quote = el("blockquote", "consistency__excerpt");
      quote.append(
        el("span", "consistency__excerpt-label", t("consistency_excerpt")),
        el("q", null, finding.excerpt),
      );
      item.append(quote);
    }
    list.append(item);
  }
  wrap.append(list);
  return wrap;
}
/* ── Report vs scorecard ───────────────────────────────────────────────
 * A report can urge moving quickly to market beside a scorecard reading 40,
 * and until this check existed nothing in the pipeline compared them: the
 * reviewer never sees the scorecard, the scorer never sees the reviewed
 * report. Each output is internally consistent, so every other guardrail
 * passes.
 */
export function renderConsistency(data) {
  const wrap = el("div", "consistency");
  wrap.append(el("p", "grounding__lede", t("consistency_lede")));
  if (!detailRecord(data) || typeof data.checked !== "boolean"
      || !detailCount(data.blockers) || !detailCount(data.warnings) || !Array.isArray(data.findings)) {
    wrap.append(detailUnavailable()); return wrap;
  }
  // Even an empty, valid findings array cannot turn a skipped/failed check
  // into agreement. The current writer normally omits skipped artifacts;
  // retained historical or hand-edited bytes still reach this read boundary.
  if (!data.checked || data.error) {
    wrap.append(el("p", "empty-note", t("detail_not_checked"))); return wrap;
  }
  const findings = data.findings;
  if (data.blockers + data.warnings !== findings.length || findings.some(f =>
    !detailRecord(f) || !["blocker", "warning"].includes(f.severity)
    || typeof f.detail !== "string" || (f.excerpt !== undefined && typeof f.excerpt !== "string"))
    || findings.filter(f => f.severity === "blocker").length !== data.blockers) {
    wrap.append(detailUnavailable()); return wrap;
  }
  if (!findings.length) {
    wrap.append(el("p", "consistency__clear", t("consistency_clear")));
    return wrap;
  }

  const list = el("ul", "consistency__list");
  for (const finding of findings) {
    const item = el("li", `consistency__item consistency__item--${finding.severity}`);
    item.append(el("p", "consistency__detail", finding.detail));
    if (finding.excerpt) {
      // Quoted, not paraphrased. The whole value of the finding is that a
      // reader can go and judge the sentence for themselves rather than
      // taking a phrase table's word for it.
      const quote = el("blockquote", "consistency__excerpt");
      quote.append(el("span", "consistency__excerpt-label", t("consistency_excerpt")));
      quote.append(el("q", null, finding.excerpt));
      item.append(quote);
    }
    list.append(item);
  }
  wrap.append(list);
  return wrap;
}

/* ── Automated checks ──────────────────────────────────────────────────
 * One panel over every check the run already performed, placed above the
 * scorecard. Each of these numbers was being written to disk and returned by
 * the API, and none of them was on screen — a reader had to know they existed
 * and go and fetch the JSON.
 *
 * Split into a pure function and a renderer so what it decides — which
 * findings outrank which, and what silence is allowed to mean — is testable
 * without a DOM.
 */
// "Not checked" is less severe than a finding, but it still outranks a pass.
// Starting the reduction at ok matters: using muted as both the unknown state
// and the initial value makes either all-clean rows or all-unchecked rows win
// for the wrong reason when the ordering changes.
const _TONE_RANK = { risk: 3, warn: 2, muted: 1, ok: 0 };

/**
 * Rows for the automated-check panel, from a run's status payload.
 *
 * Returns [] when the run produced no check at all, so the caller can leave
 * the panel out entirely rather than showing an empty box that reads as
 * "checked, nothing found".
 */
export function reliabilityRows(progress) {
  const rows = [];

  const consistency = progress.consistency;
  if (consistency == null) {
    // Distinct from "consistent". The check reads English and Chinese
    // conclusions, so a Japanese or German report simply is not covered — and
    // reporting that as a pass would be the exact overclaim this panel exists
    // to prevent.
    rows.push({ id: "consistency", tone: "muted",
                label: t("rel_consistency"), detail: t("rel_consistency_unchecked") });
  } else if (consistency.blockers > 0) {
    rows.push({ id: "consistency", tone: "risk", label: t("rel_consistency"),
                detail: t("rel_consistency_conflict").replace("{count}", consistency.blockers) });
  } else {
    rows.push({ id: "consistency", tone: "ok",
                label: t("rel_consistency"), detail: t("rel_consistency_ok") });
  }
  const review = progress.quality_review;
  if (review?.status === "fallback") {
    rows.push({ id: "review", tone: "warn", label: t("rel_review"),
                detail: t("rel_review_fallback") });
  } else if (review?.status === "partial") {
    rows.push({ id: "review", tone: "warn", label: t("rel_review"),
                detail: t("rel_review_partial")
                  .replace("{count}", review.unapplied_corrections ?? 0) });
  } else if (review?.status === "passed") {
    rows.push({ id: "review", tone: "ok", label: t("rel_review"),
                detail: t("rel_review_passed") });
  } else if (review?.status === "unavailable" || progress.source_counts) {
    // Runs produced before this field existed did not record whether the
    // reviewer completed. Absence cannot be upgraded to a historical pass.
    rows.push({ id: "review", tone: "muted", label: t("rel_review"),
                detail: t("rel_review_unknown") });
  }

  const grounding = progress.claim_grounding;
  if (grounding != null) {
    const status = grounding.status;
    const ungrounded = grounding.ungrounded ?? 0;
    const checked = grounding.checked ?? 0;
    const unverifiable = grounding.unverifiable ?? 0;
    const unavailableDomains = grounding.unavailable_domains ?? [];
    if (status === "failed" || status === "unavailable") {
      rows.push({ id: "grounding", tone: "muted", label: t("rel_grounding"),
                  detail: t("rel_grounding_unavailable") });
    } else if (status === "not_applicable") {
      rows.push({ id: "grounding", tone: "muted",
                  label: t("rel_grounding"), detail: t("rel_grounding_not_applicable") });
    } else if (ungrounded > 0) {
      rows.push({ id: "grounding", tone: "warn", label: t("rel_grounding"),
                  detail: t("rel_grounding_flagged").replace("{count}", ungrounded)
                    .replace("{checked}", checked) });
    } else if (status === "partial") {
      rows.push({ id: "grounding", tone: "muted", label: t("rel_grounding"),
                  detail: t("rel_grounding_degraded")
                    .replace("{domains}", unavailableDomains.join(", ")) });
    } else if (checked === 0) {
      // Zero unsupported out of zero checked. Shown as "nothing could be
      // checked" rather than as a clean result, because the two are opposite
      // statements that produce the same pair of numbers.
      rows.push({ id: "grounding", tone: "muted",
                  label: t("rel_grounding"), detail: t("rel_grounding_none") });
    } else if (unverifiable > 0) {
      // Some matches do not make the unchecked remainder disappear. Calling
      // this a pass was the same silence-as-success bug in a less obvious shape.
      rows.push({ id: "grounding", tone: "muted", label: t("rel_grounding"),
                  detail: t("rel_grounding_partial")
                    .replace("{checked}", checked)
                    .replace("{total}", checked + unverifiable)
                    .replace("{unverifiable}", unverifiable) });
    } else {
      rows.push({ id: "grounding", tone: "ok", label: t("rel_grounding"),
                  detail: t("rel_grounding_ok").replace("{count}", checked) });
    }
  } else if (progress.source_counts) {
    rows.push({ id: "grounding", tone: "muted", label: t("rel_grounding"),
                detail: t("rel_grounding_unknown") });
  }

  const failed = progress.failed_domains ?? [];
  const reportAudit = progress.report_audit;
  if (reportAudit == null && progress.source_counts) {
    rows.push({ id: "report-audit", tone: "muted", label: t("rel_report_audit"),
                detail: t("rel_report_audit_unknown") });
  } else if (["failed", "unavailable"].includes(reportAudit?.status)) {
    rows.push({ id: "report-audit", tone: "muted", label: t("rel_report_audit"),
                detail: t("rel_report_audit_unavailable") });
  } else if ((reportAudit?.findings ?? 0) > 0) {
    rows.push({ id: "report-audit", tone: "warn", label: t("rel_report_audit"),
                detail: t("rel_report_audit_flagged").replace("{count}", reportAudit.findings) });
  } else if (reportAudit?.status === "partial") {
    rows.push({ id: "report-audit", tone: "muted", label: t("rel_report_audit"),
                detail: t("rel_report_audit_partial")
                  .replace("{checked}", reportAudit.citation_scope_checked ?? 0)
                  .replace("{unverifiable}", reportAudit.citation_scope_unverifiable ?? 0) });
  } else if (reportAudit?.status === "not_applicable") {
    rows.push({ id: "report-audit", tone: "muted", label: t("rel_report_audit"),
                detail: t("rel_report_audit_not_applicable") });
  } else if (reportAudit?.status === "completed") {
    rows.push({ id: "report-audit", tone: "ok", label: t("rel_report_audit"),
                detail: t("rel_report_audit_clear")
                  .replace("{count}", reportAudit.citation_scope_checked ?? 0) });
  }

  if (failed.length) {
    rows.push({ id: "sources", tone: "warn", label: t("rel_sources"),
                detail: t("rel_sources_failed").replace("{domains}", failed.join(", ")) });
  } else if (progress.source_counts) {
    rows.push({ id: "sources", tone: "ok",
                label: t("rel_sources"), detail: t("rel_sources_ok") });
  }
  const authority = progress.authority_coverage;
  if (authority?.status === "incomplete") {
    const missing = (authority.missing_categories ?? []).map(
      category => t("authority_" + category),
    ).join(", ");
    rows.push({ id: "authority", tone: "warn", label: t("rel_authority"),
                detail: t("rel_authority_missing").replace("{categories}", missing) });
  } else if (authority?.status === "complete") {
    rows.push({ id: "authority", tone: "ok", label: t("rel_authority"),
                detail: t("rel_authority_complete") });
  } else if (authority == null && progress.source_counts) {
    // Old runs have no field. Absence says the check did not exist, not that
    // every required authority category was covered.
    rows.push({ id: "authority", tone: "muted", label: t("rel_authority"),
                detail: t("rel_authority_unchecked") });
  }
  const components = progress.component_coverage;
  if (components?.status === "incomplete") {
    const missing = (components.missing_components ?? []).join(", ");
    let detail = t("rel_components_missing").replace("{components}", missing);
    const unchecked = (components.unchecked_components ?? []).join(", ");
    if (unchecked) {
      detail += " " + t("rel_components_unchecked")
        .replace("{components}", unchecked);
    }
    rows.push({ id: "components", tone: "warn", label: t("rel_components"),
                detail });
  } else if (components?.status === "complete") {
    rows.push({ id: "components", tone: "ok", label: t("rel_components"),
                detail: t("rel_components_complete") });
  } else if (["partial", "unchecked"].includes(components?.status)) {
    const unchecked = (components.unchecked_components ?? []).join(", ");
    rows.push({ id: "components", tone: "muted", label: t("rel_components"),
                detail: t("rel_components_unchecked")
                  .replace("{components}", unchecked) });
  }


  if (progress.evidence_incomplete) {
    rows.push({ id: "trail", tone: "warn",
                label: t("rel_trail"), detail: t("rel_trail_incomplete") });
  }

  // The API isolates malformed summaries instead of failing the paid report.
  // Its safe null/[]/false replacements are NOT measurements. Override the
  // affected row after ordinary rendering so defaults cannot turn a read
  // fault into either a pass or a historically absent check. Names/labels are
  // code-owned; never echo damaged payloads into the diagnostic.
  const faultRows = {
    consistency: ["consistency", "rel_consistency"],
    quality_review: ["review", "rel_review"],
    claim_grounding: ["grounding", "rel_grounding"],
    report_audit: ["report-audit", "rel_report_audit"],
    authority_coverage: ["authority", "rel_authority"],
    component_coverage: ["components", "rel_components"],
    source_counts: ["sources", "rel_sources"],
    failed_domains: ["sources", "rel_sources"],
    evidence_incomplete: ["trail", "rel_trail"],
  };
  for (const field of progress.audit_metadata_unreadable ?? []) {
    if (!Object.hasOwn(faultRows, field)) continue;
    const [id, label] = faultRows[field];
    const row = { id, tone: "muted", label: t(label), detail: t("rel_metadata_unreadable") };
    const index = rows.findIndex(existing => existing.id === id);
    if (index === -1) rows.push(row);
    else if (["warn", "risk"].includes(rows[index].tone)) {
      // Source counts and failed_domains share a row. A damaged count must
      // not erase a separately readable retrieval failure in that same row.
      rows[index] = { ...rows[index], detail: rows[index].detail + " " + row.detail };
    }
    else rows[index] = row;
  }

  return rows;
}

/**
 * The panel's headline: the worst row sets the tone, and the label counts the
 * rows behind it. "Too little could be checked to say" was true but gave a
 * reader nothing to act on; "3 of 5 checks found no problem; 2 could not give
 * a result" says the same with the numbers that make it checkable.
 */
export function reliabilityVerdict(rows) {
  if (!rows.length) return { tone: "muted", label: t("rel_verdict_none") };
  const total = rows.length;
  const count = tone => rows.filter(row => row.tone === tone).length;
  const fill = (key, values) => Object.entries(values).reduce(
    (text, [name, value]) => text.replace(`{${name}}`, () => String(value)), t(key));
  const worst = rows.reduce(
    (acc, row) => (_TONE_RANK[row.tone] > _TONE_RANK[acc] ? row.tone : acc), "ok");
  if (worst === "risk") {
    return { tone: "risk", label: fill("rel_verdict_risk", { count: count("risk"), total }) };
  }
  if (worst === "warn") {
    return { tone: "warn", label: fill("rel_verdict_review", { count: count("warn"), total }) };
  }
  if (worst === "ok") {
    return { tone: "ok", note: t("rel_verdict_clear_sub"),
             label: total === 1 ? t("rel_verdict_clear_one") : fill("rel_verdict_clear", { total }) };
  }
  return { tone: "muted",
           label: fill("rel_verdict_unknown", { ok: count("ok"), muted: count("muted"), total }) };
}

/**
 * The citation check's counts as one plain line under the headline, or null.
 *
 * Shown in the panel's summary, so it is read without opening the rows. Null
 * when there is nothing countable to say: no check, a failed or unreadable
 * one, no numerical claim at all, or counts that do not add up. The row then
 * says which of those it was; a damaged count never becomes a number here.
 */
export function groundingNumbers(progress) {
  const grounding = progress.claim_grounding;
  if (!detailRecord(grounding) || (progress.audit_metadata_unreadable ?? []).includes("claim_grounding")) {
    return null;
  }
  if (["failed", "unavailable", "not_applicable"].includes(grounding.status)) return null;
  const { checked, ungrounded, unverifiable } = grounding;
  if (![checked, ungrounded, unverifiable].every(detailCount) || ungrounded > checked) return null;
  const total = checked + unverifiable;
  if (!total) return null;
  const parts = [t("rel_numbers").replace("{matched}", () => String(checked - ungrounded))
    .replace("{total}", () => String(total))];
  if (ungrounded) parts.push(t("rel_numbers_mismatch").replace("{count}", () => String(ungrounded)));
  if (unverifiable) parts.push(t("rel_numbers_unverifiable").replace("{count}", () => String(unverifiable)));
  return parts.join(t("rel_numbers_sep"));
}

export function renderReliability(progress) {
  const rows = reliabilityRows(progress);
  if (!rows.length) return null;

  const verdict = reliabilityVerdict(rows);
  // The verdict is always read before the score. The rows open by default
  // only when one of them warns; otherwise they are one click away.
  const wrap = el("details", "reliability");
  wrap.dataset.tone = verdict.tone;
  wrap.open = verdict.tone === "risk" || verdict.tone === "warn";

  const head = el("summary", "reliability__head");
  head.append(el("span", "reliability__title", t("rel_title")));
  head.append(el("strong", "reliability__verdict", verdict.label));
  head.append(el("span", "reliability__toggle", t("rel_toggle")));
  const numbers = groundingNumbers(progress);
  if (numbers) head.append(el("span", "reliability__numbers", numbers));
  wrap.append(head);

  if (verdict.note) wrap.append(el("p", "reliability__note", verdict.note));

  const list = el("ul", "reliability__rows");
  for (const row of rows) {
    const item = el("li", "reliability__row");
    item.dataset.tone = row.tone;
    item.dataset.check = row.id;
    item.append(el("span", "reliability__label", row.label));
    item.append(el("span", "reliability__detail", row.detail));
    list.append(item);
  }
  wrap.append(list);
  return wrap;
}
