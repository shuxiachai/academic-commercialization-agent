/* Result view: scorecard, report, and sources. */

import * as api from "./api.js";
import { t } from "./i18n.js";

/* ── Scoring dimensions ────────────────────────────────────────────────
 * Maxima differ per dimension (TRL is out of 9, MRL out of 10, the rest out
 * of 5), so a bar cannot assume a shared scale. Declared here rather than
 * inferred, because a wrong denominator silently misdraws the bar. */
const DIMENSIONS = [
  { key: "trl_score",            max: 9,  label: "dim_trl" },
  { key: "mrl_score",            max: 10, label: "dim_mrl" },
  { key: "patent_strength",      max: 5,  label: "dim_patent" },
  { key: "market_accessibility", max: 5,  label: "dim_market" },
  { key: "evidence_confidence",  max: 5,  label: "dim_evidence" },
];

/** Band for the headline number. Thresholds match the scorecard the Python
 *  side renders, so the same run does not get two different verdicts. */
function band(score) {
  if (score >= 70) return { name: t("band_strong"), tone: "success" };
  if (score >= 55) return { name: t("band_moderate"), tone: "accent" };
  if (score >= 40) return { name: t("band_early"), tone: "warning" };
  return { name: t("band_nascent"), tone: "muted" };
}

const el = (tag, className, text) => {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (text != null) node.textContent = text;
  return node;
};

/* ── Markdown ──────────────────────────────────────────────────────────
 * A deliberately small subset: the reports are generated by our own prompt,
 * so the shapes that appear are known. Anything unrecognised falls through
 * as a paragraph rather than being dropped.
 *
 * Input is escaped before any markup is added — the report contains model
 * output and third-party titles, and must never reach innerHTML unescaped. */
function escapeHtml(text) {
  return text
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    // Quotes matter as much as angle brackets here: inline() goes on to build
    // <a href="..."> by substitution, so a link target carrying a quote could
    // otherwise close the attribute and open an event handler beside it
    // ([x](https://e.test/" onmouseover="…)). Escaping happens before that
    // substitution runs, so the URL is already inert by the time it is placed
    // in the attribute. Report text is model output plus third-party result
    // titles and URLs — none of it is ours to trust.
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function inline(text) {
  return escapeHtml(text)
    .replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>")
    .replace(/(?<!\*)\*(?!\s)(.+?)(?<!\s)\*(?!\*)/g, "<em>$1</em>")
    .replace(/`(.+?)`/g, "<code>$1</code>")
    // Citation markers get their own affordance: they are the reason the
    // report is auditable, and running them together with prose hides that.
    .replace(/\[([APM]\d+(?:\s*,\s*[APM]\d+)*)\]/g,
             '<span class="cite">[$1]</span>')
    .replace(/\[([^\]]+)\]\((https?:\/\/[^)]+)\)/g,
             '<a href="$2" target="_blank" rel="noopener noreferrer">$1</a>');
}

export function renderMarkdown(md) {
  const out = [];
  const lines = md.split("\n");
  let paragraph = [];
  let list = null;
  let table = null;

  const flushParagraph = () => {
    if (paragraph.length) {
      out.push(`<p>${inline(paragraph.join(" "))}</p>`);
      paragraph = [];
    }
  };
  const flushList = () => {
    if (list) {
      out.push(`<ul>${list.map((i) => `<li>${inline(i)}</li>`).join("")}</ul>`);
      list = null;
    }
  };
  const flushTable = () => {
    if (table && table.rows.length) {
      const head = `<tr>${table.head.map((c) => `<th>${inline(c)}</th>`).join("")}</tr>`;
      const body = table.rows
        .map((r) => `<tr>${r.map((c) => `<td>${inline(c)}</td>`).join("")}</tr>`)
        .join("");
      out.push(`<div class="table-wrap"><table><thead>${head}</thead><tbody>${body}</tbody></table></div>`);
    }
    table = null;
  };
  const flushAll = () => { flushParagraph(); flushList(); flushTable(); };

  for (const raw of lines) {
    const line = raw.trimEnd();

    if (!line.trim()) { flushAll(); continue; }

    const heading = line.match(/^(#{1,4})\s+(.*)$/);
    if (heading) {
      flushAll();
      const level = heading[1].length;
      out.push(`<h${level}>${inline(heading[2])}</h${level}>`);
      continue;
    }

    // A separator row belongs to the table above it and renders nothing.
    if (/^\|[\s|:-]+\|$/.test(line)) continue;

    if (line.startsWith("|") && line.endsWith("|")) {
      const cells = line.slice(1, -1).split("|").map((c) => c.trim());
      flushParagraph(); flushList();
      if (!table) table = { head: cells, rows: [] };
      else table.rows.push(cells);
      continue;
    }
    flushTable();

    const item = line.match(/^\s*[-*]\s+(.*)$/);
    if (item) {
      flushParagraph();
      (list ??= []).push(item[1]);
      continue;
    }
    flushList();

    paragraph.push(line.trim());
  }
  flushAll();
  return out.join("\n");
}

/* ── Scorecard ─────────────────────────────────────────────────────── */

function renderScorecard(scores) {
  const wrap = el("section", "scorecard");
  const overall = Number(scores.overall_score ?? 0);
  const { name, tone } = band(overall);

  const head = el("div", "scorecard__head");
  const figure = el("div", "scorecard__figure");
  figure.dataset.tone = tone;
  figure.append(
    el("span", "scorecard__value tabular", overall.toFixed(1)),
    el("span", "scorecard__denom", "/ 100"),
  );
  const caption = el("div", "scorecard__caption");
  caption.append(
    el("span", "scorecard__band", name),
    el("span", "scorecard__label", t("readiness")),
  );
  head.append(figure, caption);
  wrap.append(head);

  const grid = el("div", "dims");
  for (const dim of DIMENSIONS) {
    const value = Number(scores[dim.key] ?? 0);
    const pct = Math.max(0, Math.min(100, (value / dim.max) * 100));

    const row = el("div", "dim");
    const label = el("div", "dim__label", t(dim.label));
    const bar = el("div", "dim__bar");
    const fill = el("div", "dim__fill");
    fill.style.width = `${pct}%`;
    bar.append(fill);
    const num = el("div", "dim__value tabular", `${value} / ${dim.max}`);

    row.append(label, bar, num);

    const rationale = scores[dim.key.replace(/_score$|_strength$|_accessibility$|_confidence$/, "") + "_rationale"];
    if (rationale) row.title = rationale;

    grid.append(row);
  }
  wrap.append(grid);

  for (const [key, title] of [["key_risks", t("risks")], ["key_opportunities", t("opportunities")]]) {
    const items = scores[key];
    if (!Array.isArray(items) || !items.length) continue;
    const block = el("div", "notes");
    block.append(el("h4", "notes__title", title));
    const ul = el("ul", "notes__list");
    for (const item of items) ul.append(el("li", null, item));
    block.append(ul);
    wrap.append(block);
  }

  return wrap;
}

/* ── Public ────────────────────────────────────────────────────────── */

export async function render(container, runId, { artifacts }) {
  container.innerHTML = "";

  const tabs = el("div", "tabs");
  const panels = el("div", "panels");

  const views = [];
  if (artifacts.includes("scores")) views.push({ id: "score", label: t("tab_score") });
  if (artifacts.includes("report")) views.push({ id: "report", label: t("tab_report") });
  if (artifacts.includes("sources")) views.push({ id: "sources", label: t("tab_sources") });
  if (artifacts.includes("grounding"))
    views.push({ id: "grounding", label: t("tab_grounding") });

  if (!views.length) {
    container.append(el("p", "empty-note", t("no_artifacts")));
    return;
  }

  for (const view of views) {
    const tab = el("button", "tab", view.label);
    tab.type = "button";
    tab.dataset.view = view.id;
    tab.addEventListener("click", () => select(view.id));
    tabs.append(tab);

    const panel = el("div", "panel");
    panel.dataset.view = view.id;
    panel.hidden = true;
    panels.append(panel);
  }

  container.append(tabs, panels);

  const loaded = new Set();

  async function select(id) {
    for (const tab of tabs.children) tab.dataset.active = String(tab.dataset.view === id);
    for (const panel of panels.children) panel.hidden = panel.dataset.view !== id;

    if (loaded.has(id)) return;
    loaded.add(id);

    const panel = panels.querySelector(`[data-view="${id}"]`);
    panel.append(el("div", "skeleton", ""));

    try {
      if (id === "score") {
        const scores = await api.getArtifact(runId, "scores");
        panel.innerHTML = "";
        panel.append(renderScorecard(scores));
      } else if (id === "report") {
        const md = await api.getReport(runId);
        panel.innerHTML = `<article class="prose">${renderMarkdown(md)}</article>`;
      } else if (id === "grounding") {
        const grounding = await api.getArtifact(runId, "grounding");
        panel.innerHTML = "";
        panel.append(renderGrounding(grounding));
      } else {
        const sources = await api.getArtifact(runId, "sources");
        panel.innerHTML = "";
        panel.append(renderSources(sources));
      }
    } catch (err) {
      panel.innerHTML = "";
      panel.append(el("p", "empty-note", err.message));
      loaded.delete(id);      // let a retry re-fetch
    }
  }

  select(views[0].id);
}

/* ── Citation check ────────────────────────────────────────────────────
 * What the server could and could not verify about the report's numbers.
 *
 * The counts are shown together on purpose. "0 unsupported" alone reads as a
 * clean bill of health, when next to a large "could not check" it means the
 * screen mostly did not run — a different statement, and the one a reader
 * needs in order to know how much the first number is worth.
 */

// Exported for the same reason renderMarkdown is: the app calls it only
// through render(), but what it decides — how three counts are presented
// relative to each other — is worth asserting on directly.
export function renderGrounding(data) {
  const wrap = el("div", "grounding");

  const checked = data.checked ?? 0;
  const ungrounded = data.ungrounded ?? 0;
  const unverifiable = data.unverifiable ?? 0;

  wrap.append(el("p", "grounding__lede", t("grounding_lede")));

  const stats = el("div", "grounding__stats");
  for (const [value, label, tone] of [
    [checked, t("grounding_checked"), "ok"],
    [ungrounded, t("grounding_ungrounded"), ungrounded ? "warn" : "ok"],
    [unverifiable, t("grounding_unverifiable"), "muted"],
  ]) {
    const cell = el("div", `grounding__stat grounding__stat--${tone}`);
    cell.append(el("div", "grounding__value", String(value)));
    cell.append(el("div", "grounding__label", label));
    stats.append(cell);
  }
  wrap.append(stats);

  // Per domain, because one aggregate cannot say both "the check works" and
  // "market reports have no abstract to check against".
  const byDomain = data.by_domain ?? {};
  const domains = [
    ["academic", t("group_academic")],
    ["patent", t("group_patents")],
    ["market", t("group_market")],
  ].filter(([key]) => byDomain[key]);

  if (domains.length) {
    const list = el("ul", "grounding__domains");
    for (const [key, label] of domains) {
      const d = byDomain[key];
      const total = (d.checked ?? 0) + (d.unverifiable ?? 0);
      const text = total
        ? `${label}: ${d.checked}/${total} ${t("grounding_checkable")}`
        : `${label}: ${t("grounding_no_figures")}`;
      list.append(el("li", "grounding__domain", text));
    }
    wrap.append(list);
  }

  const rows = data.findings ?? [];
  if (!rows.length) return wrap;

  const list = el("ul", "grounding__list");
  for (const row of rows) {
    const item = el("li", `grounding__item grounding__item--${row.status}`);
    item.append(el("span", "grounding__id", `${row.finding_id}`));
    item.append(el("span", "grounding__claim", row.claim ?? ""));
    const why = row.status === "ungrounded"
      ? t("grounding_missing").replace("{figures}",
          (row.ungrounded_figures ?? []).join(", "))
      : row.unverifiable_reason ?? "";
    if (why) item.append(el("span", "grounding__why", why));
    list.append(item);
  }
  wrap.append(el("h3", "sources__title", t("grounding_detail")));
  wrap.append(list);
  return wrap;
}

/* ── Sources ───────────────────────────────────────────────────────── */

function renderSources(collection) {
  const wrap = el("div", "sources");

  const groups = [
    ["academic_sources", t("group_academic")],
    ["patent_sources", t("group_patents")],
    ["market_sources", t("group_market")],
  ];

  for (const [key, title] of groups) {
    const items = collection[key] ?? [];
    if (!items.length) continue;

    wrap.append(el("h3", "sources__title", `${title} · ${items.length}`));
    const list = el("ul", "sources__list");

    for (const source of items) {
      const li = el("li", "source");

      const id = el("span", "source__id", source.source_id);
      const body = el("div", "source__body");

      const link = el("a", "source__link", source.title);
      link.href = source.url;
      link.target = "_blank";
      link.rel = "noopener noreferrer";

      const meta = el("div", "source__meta");
      const bits = [source.publisher, source.published_date?.slice(0, 4)].filter(Boolean);
      meta.append(el("span", null, bits.join(" · ")));

      const tier = el("span", "tier", source.credibility_tier);
      tier.dataset.tier = source.credibility_tier;
      meta.append(tier);

      body.append(link, meta);
      li.append(id, body);
      list.append(li);
    }
    wrap.append(list);
  }
  return wrap;
}
